#!/usr/bin/env python3
"""Generate terrain_data.gd from 'Kingdom Map.jpg'.

Usage (from the project root):
    pip install pillow numpy scipy
    python tools/generate_terrain.py

Every pixel of the (downscaled) map is classified into a terrain type.
Re-run this whenever you repaint the map image.
"""
import colorsys
import sys
from pathlib import Path

import numpy as np
from PIL import Image
from scipy import ndimage

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "Kingdom Map.jpg"
OUT = ROOT / "terrain_data.gd"

GW, GH = 256, 172          # grid size in tiles (keeps the image aspect ratio)
OCEAN, SHALLOW, LAKE, GRASS, FOREST, MOUNTAIN, DESERT = range(7)
LAND_TYPES = [GRASS, FOREST, MOUNTAIN, DESERT]


def classify(path: Path) -> np.ndarray:
    im = Image.open(path).convert("RGB").resize((GW, GH), Image.BOX)
    a = np.asarray(im).astype(float) / 255.0
    hsv = np.zeros_like(a)
    for y in range(GH):
        for x in range(GW):
            hsv[y, x] = colorsys.rgb_to_hsv(*a[y, x])
    h, s, v = hsv[..., 0] * 360, hsv[..., 1], hsv[..., 2]

    water = (h >= 175) & (h <= 255) & (s > 0.28)
    land = ~water

    # Ocean = water connected to the image border; the rest is lakes/rivers.
    lab, _ = ndimage.label(water)
    border = set(lab[0, :]) | set(lab[-1, :]) | set(lab[:, 0]) | set(lab[:, -1])
    border.discard(0)
    ocean = np.isin(lab, list(border))
    lake = water & ~ocean

    grid = np.full((GH, GW), GRASS, dtype=np.uint8)
    desert = land & (h >= 20) & (h <= 50) & (v > 0.72)
    forest = land & (h >= 70) & (h <= 150) & (v < 0.40)
    rock = land & (
        ((s < 0.22) & (v > 0.38))
        | ((h >= 10) & (h <= 45) & (v <= 0.72) & (v > 0.30) & (s > 0.25))
    )
    grid[desert] = DESERT
    grid[forest] = FOREST
    grid[rock] = MOUNTAIN
    grid[lake] = LAKE

    dist = ndimage.distance_transform_edt(ocean)
    grid[ocean] = OCEAN
    grid[ocean & (dist <= 3)] = SHALLOW      # shallow water near the coast

    # 3x3 majority filter on land tiles to remove single-tile speckles.
    out = grid.copy()
    for y in range(1, GH - 1):
        for x in range(1, GW - 1):
            if grid[y, x] in LAND_TYPES:
                win = grid[y - 1:y + 2, x - 1:x + 2].ravel()
                win = win[np.isin(win, LAND_TYPES)]
                if len(win):
                    out[y, x] = np.bincount(win).argmax()
    return out


def write_gd(grid: np.ndarray) -> None:
    rows = ['\t"' + "".join(str(int(c)) for c in row) + '"' for row in grid]
    body = ",\n".join(rows)
    text = f'''class_name TerrainData
extends RefCounted
## AUTO-GENERATED by tools/generate_terrain.py - do not edit by hand.

const WIDTH := {GW}
const HEIGHT := {GH}

enum {{ OCEAN, SHALLOW, LAKE, GRASS, FOREST, MOUNTAIN, DESERT }}

const NAMES := ["Ocean", "Shallow Water", "Lake", "Grassland", "Forest", "Mountain", "Desert"]

const ROWS := [
{body},
]


static func get_type(x: int, y: int) -> int:
	if x < 0 or y < 0 or x >= WIDTH or y >= HEIGHT:
		return OCEAN
	return ROWS[y].unicode_at(x) - 48


static func is_water(t: int) -> bool:
	return t <= LAKE


static func is_sea(t: int) -> bool:
	return t <= SHALLOW


static func is_land(t: int) -> bool:
	return t >= GRASS
'''
    OUT.write_text(text, encoding="utf-8")


if __name__ == "__main__":
    g = classify(SRC)
    write_gd(g)
    counts = {n: int((g == i).sum()) for i, n in enumerate(
        ["ocean", "shallow", "lake", "grass", "forest", "mountain", "desert"])}
    print("wrote", OUT, counts)
